/**
 * Generates every derived artifact of the demo catalog from `catalog.json`:
 *
 * - `src/catalog.generated.ts`: the `DemoAssetDefinitions` type, the category
 *   table and the URL-parameterized builders behind the factories;
 * - `src/standard.generated.ts`: the default instance, one literal
 *   `new URL(..., import.meta.url)` per file so bundlers can see and emit it;
 * - `manifest.json`: every shipped file with hash, size, role and provenance;
 * - `THIRD_PARTY_NOTICES.md`: attribution for exactly the shipped files.
 *
 * Usage:
 *   tsx scripts/generate.ts           write the generated sources
 *   tsx scripts/generate.ts --check   fail when a generated source is stale
 *   tsx scripts/generate.ts --media   also copy the standard media into media/
 */
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  bytesOf,
  type DemoAssetProfile,
  filesFor,
  packageRoot,
  resolveCatalog,
  type ResolvedCatalog,
  type ResolvedEntry,
  sha256Of,
} from './catalog.ts';

const RESOURCE_TYPES: Readonly<Record<string, { readonly wrapper: string; readonly resource: string }>> = {
  texture: { wrapper: 'ResourceAsset', resource: 'Texture' },
  sound: { wrapper: 'ResourceAsset', resource: 'Sound' },
  json: { wrapper: 'ValueAsset', resource: 'unknown' },
  music: { wrapper: 'LeaflessAsset', resource: 'AudioStream' },
  video: { wrapper: 'LeaflessAsset', resource: 'Video' },
  font: { wrapper: 'LeaflessAsset', resource: 'FontFace' },
  bmFont: { wrapper: 'LeaflessAsset', resource: 'BmFont' },
  svg: { wrapper: 'LeaflessAsset', resource: 'HTMLImageElement' },
};

const HEADER = '// Generated by scripts/generate.ts from catalog.json. Do not edit by hand.\n';

const quote = (value: string): string => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;

const descriptorType = (entry: ResolvedEntry): string => {
  const shape = RESOURCE_TYPES[entry.type]!;

  return `${shape.wrapper}<${entry.valueType ?? shape.resource}>`;
};

const typeImports = (entries: readonly ResolvedEntry[]): string[] => {
  const names = new Set<string>();

  for (const entry of entries) {
    const shape = RESOURCE_TYPES[entry.type]!;
    names.add(shape.wrapper);
    const resource = entry.valueType ?? shape.resource;

    if (/^[A-Z]/.test(resource) && resource !== 'FontFace' && resource !== 'HTMLImageElement') {
      names.add(resource);
    }
  }

  return [...names].sort();
};

/** The value types named in `Asset.type<T>(...)` generics, which a generated module must import itself. */
const valueTypeImports = (entries: readonly ResolvedEntry[]): string[] =>
  [...new Set(entries.flatMap(entry => (entry.valueType === undefined ? [] : [entry.valueType])))].sort();

const describe = (catalog: ResolvedCatalog, entry: ResolvedEntry): string => {
  const provenance = catalog.source.provenance[entry.provenance]!;
  const size =
    entry.bytes >= 1_000_000 ? `${(entry.bytes / 1_000_000).toFixed(1)} MB` : `${Math.max(1, Math.round(entry.bytes / 1000))} kB`;
  const loads = entry.type === 'texture' || entry.type === 'sound' ? '`loader.get()` or `await loader.load()`' : 'await `loader.load()`';
  const extra = entry.transitive.length > 0 ? ` Also fetches ${entry.transitive.map(path => `\`${path}\``).join(', ')}.` : '';

  return `  /** \`${entry.path}\` (${size}). ${provenance.title}, ${provenance.license}. Load with ${loads}.${extra} */`;
};

const urlExpression = (entry: ResolvedEntry, url: (path: string) => string): string => {
  const options = Object.entries(entry.options ?? {});
  const generic = entry.valueType === undefined ? '' : `<${entry.valueType}>`;
  const args = [quote(entry.type), url(entry.path)];

  if (options.length > 0) {
    const rendered = options
      .map(
        ([name, value]) =>
          `${name}: ${typeof value === 'object' ? url(value.$path) : typeof value === 'string' ? quote(value) : String(value)}`,
      )
      .join(', ');
    args.push(`{ ${rendered} }`);
  }

  return `Asset.type${generic}(${args.join(', ')})`;
};

const renderInterface = (catalog: ResolvedCatalog, name: string, profile: DemoAssetProfile, doc: string): string => {
  const entries = catalog.entries.filter(entry => entry.profile === profile);

  return [
    `/**\n${doc}\n */`,
    `export interface ${name} {`,
    ...entries.flatMap(entry => [describe(catalog, entry), `  readonly ${entry.key}: ${descriptorType(entry)};`]),
    '}',
  ].join('\n');
};

const renderBuilder = (catalog: ResolvedCatalog, name: string, typeName: string, profile: DemoAssetProfile): string => {
  const entries = catalog.entries.filter(entry => entry.profile === profile);

  return [
    `/** @internal */`,
    `export const ${name} = (url: (path: string) => string): ${typeName} =>`,
    '  Object.freeze({',
    ...entries.map(entry => `    ${entry.key}: ${urlExpression(entry, path => `url(${quote(path)})`)},`),
    '  });',
  ].join('\n');
};

/** Renders `src/catalog.generated.ts`. */
export const renderCatalogModule = (catalog: ResolvedCatalog): string => {
  const standard = catalog.entries.filter(entry => entry.profile === 'standard');
  const categories = [...new Set(standard.map(entry => entry.category))];
  const imports = typeImports(catalog.entries);

  return `${[
    HEADER,
    `import type { ${imports.join(', ')} } from '@codexo/exojs';`,
    `import { Asset } from '@codexo/exojs';`,
    '',
    renderInterface(
      catalog,
      'DemoAssetDefinitions',
      'standard',
      [
        ' * The standard demo media, one readonly asset descriptor per file.',
        ' *',
        ' * Reading a property only returns its descriptor: nothing is fetched, decoded or',
        ' * allocated until a loader is handed the descriptor. Textures and sounds can be',
        ' * claimed synchronously with `loader.get()`; video, music, fonts, bitmap fonts and',
        ' * SVG images have no synchronous handle and load with `await loader.load()`.',
      ].join('\n'),
    ),
    '',
    `/** The name of one standard demo asset. */`,
    `export type DemoAssetKey = keyof DemoAssetDefinitions;`,
    '',
    `/** The browsing category a demo asset is listed under. */`,
    `export type DemoAssetCategory = ${categories.map(quote).join(' | ')};`,
    '',
    `/** The category of every standard demo asset, for browsers and filters. Static data; reading it loads nothing. */`,
    `export const demoAssetCategories: Readonly<Record<DemoAssetKey, DemoAssetCategory>> = Object.freeze({`,
    ...standard.map(entry => `  ${entry.key}: ${quote(entry.category)},`),
    '});',
    '',
    renderBuilder(catalog, 'buildDemoAssets', 'DemoAssetDefinitions', 'standard'),
    '',
    renderInterface(
      catalog,
      'ExtendedDemoAssetDefinitions',
      'extended',
      [
        ' * The extended demo media, hosted separately from the npm package.',
        ' *',
        ' * These files are not in the package tarball: download the extended media archive,',
        ' * serve it, and pass its location to `createExtendedDemoAssets()`.',
      ].join('\n'),
    ),
    '',
    renderBuilder(catalog, 'buildExtendedDemoAssets', 'ExtendedDemoAssetDefinitions', 'extended'),
    '',
  ].join('\n')}`;
};

/** Renders `src/standard.generated.ts`. */
export const renderStandardModule = (catalog: ResolvedCatalog): string => {
  const standard = catalog.entries.filter(entry => entry.profile === 'standard');
  const imports = valueTypeImports(standard);
  const valueTypeLine = imports.length === 0 ? '' : `import type { ${imports.join(', ')} } from '@codexo/exojs';`;

  return `${[
    HEADER,
    valueTypeLine,
    `import { Asset } from '@codexo/exojs';`,
    '',
    `import type { DemoAssetDefinitions } from './catalog.generated.js';`,
    '',
    '// One literal `new URL(..., import.meta.url)` per file is what lets a bundler',
    '// find, copy and rewrite each media file; a computed path would hide them.',
    '/**',
    ' * The standard demo assets, resolved against the media shipped inside this',
    ' * package. Importing or reading it fetches nothing; hand a descriptor to a',
    ' * loader to load it.',
    ' *',
    ' * @example',
    ' * ```ts',
    " * import { demoAssets as assets } from '@codexo/exojs-demo-assets';",
    ' *',
    ' * const ship = new Sprite(this.loader.get(assets.ship));',
    ' * const video = await this.loader.load(assets.videoHighRes);',
    ' * ```',
    ' */',
    'export const demoAssets: DemoAssetDefinitions = Object.freeze({',
    ...standard.map(
      entry => `  ${entry.key}: ${urlExpression(entry, path => `new URL(${quote(`../media/${path}`)}, import.meta.url).href`)},`,
    ),
    '});',
    '',
  ].join('\n')}`;
};

/** Renders `manifest.json`. */
export const renderManifest = (catalog: ResolvedCatalog, version: string): string => {
  const profile = (name: DemoAssetProfile): object => {
    const files = filesFor(catalog, name);

    return { files: files.length, bytes: bytesOf(files) };
  };

  return `${JSON.stringify(
    {
      schemaVersion: 1,
      package: '@codexo/exojs-demo-assets',
      version,
      profiles: { standard: profile('standard'), extended: profile('extended') },
      entries: catalog.entries.map(entry => ({
        key: entry.key,
        type: entry.type,
        category: entry.category,
        profile: entry.profile,
        path: entry.path,
        bytes: entry.bytes,
        sha256: entry.sha256,
        provenance: entry.provenance,
        ...(entry.options === undefined ? {} : { options: entry.options }),
        ...(entry.transitive.length === 0 ? {} : { transitive: entry.transitive }),
        ...(catalog.source.media[entry.path] === undefined ? {} : { media: catalog.source.media[entry.path] }),
      })),
      files: catalog.files,
      provenance: catalog.source.provenance,
      blocked: catalog.source.blocked,
    },
    null,
    2,
  )}\n`;
};

/** Renders the notices for one profile: every provenance record that one of its files uses. */
export const renderNotices = (catalog: ResolvedCatalog, profiles: readonly DemoAssetProfile[]): string => {
  const files = catalog.files.filter(file => profiles.includes(file.profile));
  const byProvenance = new Map<string, string[]>();

  for (const file of files) {
    byProvenance.set(file.provenance, [...(byProvenance.get(file.provenance) ?? []), file.path]);
  }

  const sections = [...byProvenance.entries()].map(([id, paths]) => {
    const record = catalog.source.provenance[id]!;
    const lines = [
      `## ${record.title}`,
      '',
      `- Author: ${record.author}`,
      `- License: ${record.license} (${record.licenseUrl})`,
      `- Source: ${record.source}`,
      ...(record.attribution === undefined ? [] : [`- Attribution: ${record.attribution}`]),
      ...(record.note === undefined ? [] : [`- Note: ${record.note}`]),
      '',
      'Files:',
      '',
      ...paths.map(path => `- \`${path}\``),
    ];

    return lines.join('\n');
  });

  const licenseTexts = files
    .filter(file => file.role === 'license')
    .map(file => {
      const text = readFileSync(resolve(catalog.sourceRoot, file.path), 'utf8')
        .replace(/\r\n?/g, '\n')
        .replace(/[ \t]+$/gm, '')
        .replace(/\n*$/, '');

      return `### ${file.path}\n\n\`\`\`text\n${text}\n\`\`\`\n`;
    });

  return `${[
    '# Third-Party Notices',
    '',
    'Attribution for every media file this delivery contains. Paths are relative to the media root',
    '(`media/` in the npm package, the archive root in a media archive). Files whose license is',
    'MIT are original ExoJS work.',
    '',
    ...sections.flatMap(section => [section, '']),
    ...(licenseTexts.length === 0 ? [] : ['## License texts', '', ...licenseTexts]),
  ].join('\n')}`;
};

const readVersion = (): string => (JSON.parse(readFileSync(resolve(packageRoot, 'package.json'), 'utf8')) as { version: string }).version;

/** Every generated file with its rendered content, keyed by package-relative path. */
export const renderAll = (catalog: ResolvedCatalog = resolveCatalog()): Record<string, string> => ({
  'src/catalog.generated.ts': renderCatalogModule(catalog),
  'src/standard.generated.ts': renderStandardModule(catalog),
  'manifest.json': renderManifest(catalog, readVersion()),
  'THIRD_PARTY_NOTICES.md': renderNotices(catalog, ['standard']),
});

/** Replaces `media/` with exactly the standard files, verifying each copy against its manifest hash. */
export const copyStandardMedia = (catalog: ResolvedCatalog, target: string): number => {
  rmSync(target, { recursive: true, force: true });

  for (const file of filesFor(catalog, 'standard')) {
    const destination = resolve(target, file.path);
    mkdirSync(dirname(destination), { recursive: true });
    copyFileSync(resolve(catalog.sourceRoot, file.path), destination);

    if (sha256Of(destination) !== file.sha256) {
      throw new Error(`${file.path}: copy does not match its manifest hash`);
    }
  }

  return filesFor(catalog, 'standard').length;
};

const main = (): void => {
  const args = new Set(process.argv.slice(2));
  const catalog = resolveCatalog();
  const rendered = renderAll(catalog);
  const stale: string[] = [];

  for (const [path, content] of Object.entries(rendered)) {
    const target = resolve(packageRoot, path);
    let current: string;

    try {
      current = readFileSync(target, 'utf8');
    } catch {
      current = '';
    }

    if (current === content) {
      continue;
    }

    if (args.has('--check')) {
      stale.push(path);
    } else {
      writeFileSync(target, content, 'utf8');
      process.stdout.write(`[demo-assets] wrote ${path}\n`);
    }
  }

  if (stale.length > 0) {
    process.stderr.write(
      `[demo-assets] stale generated files (run \`pnpm --filter @codexo/exojs-demo-assets generate\`): ${stale.join(', ')}\n`,
    );
    process.exit(1);
  }

  if (args.has('--media')) {
    const count = copyStandardMedia(catalog, resolve(packageRoot, 'media'));
    process.stdout.write(`[demo-assets] copied ${count} standard media files into media/\n`);
  }
};

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
